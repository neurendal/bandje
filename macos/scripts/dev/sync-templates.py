#!/usr/bin/env python3 -I
"""Copies the iPhone app's example summary templates into the Mac app, word for word.

  python3 -I scripts/dev/sync-templates.py [path/to/SummaryTemplates.json]

Source (default): ~/Code/Claude/projects/bandje-ios/Bandje/SummaryTemplates.json, one entry per
language: {"fileWord": ..., "templates": [{"name", "text"} x 4]} (meeting, job interview, customer
interview, generic summary). Writes Sources/Bandje/SummaryTemplates.swift, which holds the JSON as is,
so both apps seed the same examples into the shared Templates folder.
"""
import json, os, sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
src = sys.argv[1] if len(sys.argv) > 1 else os.path.expanduser("~/Code/Claude/projects/bandje-ios/Bandje/SummaryTemplates.json")
text = open(src, encoding="utf-8").read()
data = json.loads(text)
for lang, v in data.items():
    assert v["fileWord"] and len(v["templates"]) == 4, lang
assert '"""#' not in text
body = "\n".join(("    " + line) if line else "" for line in text.rstrip("\n").split("\n"))
out = f'''// Generated by scripts/dev/sync-templates.py from the iPhone app's Bandje/SummaryTemplates.json.
// Do not edit: change the iPhone file and run the script again.

/// The example summary templates and the summary file word per language, the same data as on the
/// iPhone (meeting, job interview, customer interview, generic summary).
enum SummaryTemplateData {{
    static let json = #"""
{body}
    """#
}}
'''
open(os.path.join(ROOT, "Sources", "Bandje", "SummaryTemplates.swift"), "w", encoding="utf-8").write(out)
print("languages:", ", ".join(sorted(data)))
